"""Regenerate docs/mcp/tool-inventory.md from the live Unreal MCP server.

Usage (repo root, editor running):
  python Tools/mcp/gen_inventory.py
"""

from __future__ import annotations

import datetime
import re
import sys
from pathlib import Path
from typing import Any

from beacon_mcp import Client, ToolError

# Shorter "sentences" are usually an abbreviation cut at its full stop.
MIN_SENTENCE_CHARS = 25
OUTPUT = Path(__file__).resolve().parents[2] / "docs" / "mcp" / "tool-inventory.md"


def one_line(description: str | None, limit: int = 150) -> str:
    """First sentence of a tool description, safe for a Markdown table cell."""
    paragraph = (description or "").replace("\r", "").strip().split("\n\n")[0]
    text = " ".join(line.strip() for line in paragraph.split("\n")).strip()
    text = text.replace("�", "-").replace("|", "\\|")
    sentence = re.match(r"(.+?[.!?])(\s|$)", text)
    if sentence and len(sentence.group(1)) >= MIN_SENTENCE_CHARS:
        text = sentence.group(1)
    if len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text or "(no description)"


def render(toolsets: list[tuple[str, dict[str, Any] | None, str | None]], today: str) -> str:
    total = sum(len(described["tools"]) for _, described, _ in toolsets if described)
    lines = [
        "# Unreal MCP tool inventory",
        "",
        f"Taken from the live UE 5.8 editor MCP server on {today} with the All Toolsets plugin "
        "enabled, by calling `list_toolsets` and then `describe_toolset` for each toolset. The server "
        f"reported **{len(toolsets)} toolsets** and **{total} tools**. Each purpose is the first "
        "sentence of the tool's own description.",
        "",
        "Every tool is reached through `call_tool` with the toolset name and the short tool name "
        "shown here. This file is generated by `Tools/mcp/gen_inventory.py`; regenerate it after an "
        "engine or plugin upgrade instead of editing it by hand.",
        "",
        "## Summary",
        "",
        "| Toolset | Tools | Purpose |",
        "|---|---|---|",
    ]
    for name, described, error in toolsets:
        count = len(described["tools"]) if described else "error"
        purpose = one_line(described["description"], 160) if described else (error or "")
        lines.append(f"| `{name}` | {count} | {purpose} |")
    for name, described, error in toolsets:
        lines += ["", f"## {name}", ""]
        if described is None:
            lines.append(f"`describe_toolset` failed: `{error}`")
        elif not described["tools"]:
            lines.append("The toolset reported no tools.")
        else:
            lines += ["| Tool | Purpose |", "|---|---|"]
            lines += [
                f"| `{tool['name'].split('.')[-1]}` | {one_line(tool.get('description'))} |"
                for tool in described["tools"]
            ]
    return "\n".join(lines) + "\n"


def main() -> int:
    client = Client()
    toolsets: list[tuple[str, dict[str, Any] | None, str | None]] = []
    for name in client.list_toolsets():
        try:
            toolsets.append((name, client.describe(name), None))
        except ToolError as error:
            toolsets.append((name, None, str(error)))
    today = datetime.datetime.now(tz=datetime.UTC).date().isoformat()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(toolsets, today), encoding="utf-8", newline="\n")
    failed = [name for name, described, _ in toolsets if described is None]
    print(f"{OUTPUT}: {len(toolsets)} toolsets, {len(failed)} failed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
